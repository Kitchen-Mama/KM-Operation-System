/**
 * ==================================================================================================
 * S3-R11 — THE INTERACTION RUNNER: REAL BROWSER, REAL ROUTER, POPULATED CONTROLS
 * ==================================================================================================
 *
 * S3-R3's runner proved the lifecycle shape of twelve pages. It could not answer THIS round's
 * question, because its stub answers `{ success:true, data:{} }` — every page mounts over an empty
 * world, so there is no row to filter, no SKU to switch to and no tab to render. §2 says so in as
 * many words: "no stub that returns empty rows if interaction requires populated controls".
 *
 * So this runner keeps S3-R3's honest choke point (window.fetch, in <head>, before any application
 * script) and replaces the payload with a PRODUCTION-SHAPED FIXTURE WORLD: 120 master SKUs, 360
 * marketplace SKUs across 3 countries x 2 marketplaces, 360 regional detail rows and 360 pricing
 * rows, carried under the canonical camelCase workspace keys the shipped adapters consume. Nothing
 * else is substituted. The shell, the script order, the router, the lifecycle epochs, km-transport,
 * every page module and every adapter are production.
 *
 * WHAT IS MEASURED, AND WHY IT IS HONEST
 *
 *   ms        performance.now() around a real interaction, in a real browser, over real rows. This
 *             is CLIENT cost. It is NOT a production latency number and this file never claims to be
 *             one: SERVER_MS is an injected constant, so a measured entry time is client work plus a
 *             number I chose. What the operator's own capture owns is the server half; what this
 *             owns is everything after the bytes arrive, which is the half a code change can move.
 *
 *   api       requests that reached the Apps Script endpoint, counted per interaction window and
 *             broken down by action. THIS is the number that survives the injected constant: a
 *             request count is a property of the control flow, not of the latency, so "this
 *             interaction issues two reads for one table" is true at any SERVER_MS.
 *
 *   dupes     the same action+table dispatched more than once inside one interaction window.
 *
 * SERVER_MS is deliberately a knob rather than 0. At 0 a duplicate read is invisible in the ms and
 * visible only in the count; at 400 the count becomes the latency, which is the whole argument of
 * this round. Both are run.
 *
 * USAGE:  node assets/tests/_s3r11-interaction-runner.js [serverMs]   → one JSON blob
 * A helper, not a suite: the leading underscore keeps the sweep from executing it.
 * ==================================================================================================
 */
