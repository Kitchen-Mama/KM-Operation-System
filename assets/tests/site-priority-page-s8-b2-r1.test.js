function El(id) {
  this.id = id || ''; this.value = ''; this.hidden = false; this.textContent = ''; this.innerHTML = '';
  this.className = ''; this._attrs = {}; this._listeners = {};
  this.classList = { _s: {}, add: function (c) { this._s[c] = 1; }, remove: function (c) { delete this._s[c]; },
    contains: function (c) { return !!this._s[c]; } };
}
El.prototype.getAttribute = function (k) { return Object.prototype.hasOwnProperty.call(this._attrs, k) ? this._attrs[k] : null; };
El.prototype.setAttribute = function (k, v) { this._attrs[k] = String(v); };
El.prototype.addEventListener = function (t, fn) { (this._listeners[t] = this._listeners[t] || []).push(fn); };
El.prototype.listenerCount = function (t) { return (this._listeners[t] || []).length; };
El.prototype.fire = function (t, target) {
  var ls = this._listeners[t] || [];
  for (var i = 0; i < ls.length; i++) ls[i]({ target: target });
  return ls.length;
};

function makeDom() {
  var byId = {};
  ['site-priority-section', 'sp-status', 'sp-rows', 'sp-empty', 'sp-filter-company', 'sp-filter-country', 'sp-refresh']
    .forEach(function (id) { byId[id] = new El(id); });
  var extra = [];                                   // nodes a test injects, e.g. the edit input
  return {
    byId: byId, extra: extra,
    document: {
      getElementById: function (id) { return byId[id] || null; },
      querySelector: function (sel) {
        for (var i = 0; i < extra.length; i++) if (extra[i]._sel === sel) return extra[i];
        return null;
      },
      querySelectorAll: function (sel) {
        return extra.filter(function (e) { return e._sel === sel || (sel === '[data-sp-input]' && e._isInput); });
      }
    }
  };
}

// Load the page module against a fresh global. Returns { api, dom, calls }.
function bootPage(opts) {
  opts = opts || {};
  var dom = makeDom();
  var calls = { upsert: [], refresh: 0 };
  var win = {};
  win.KM = {
    lifecycle: { register: function (name, hooks) { win.KM._hooks = hooks; win.KM._registered = name; } },
    partialLoader: { loadPartial: function () { return Promise.resolve(true); } },
    countryIdentity: require(path.join(ROOT, 'assets', 'js', 'core', 'supply-planning-country-identity.js')),
    DB: {
      getMarketplaces: function () { return (opts.rows || []).slice(); },
      refreshOperationDb: function () { calls.refresh++; if (opts.onRefresh) opts.onRefresh(); return Promise.resolve(true); },
      upsertMarketplace: function (payload) {
        calls.upsert.push(payload);
        if (opts.upsertThrows) return Promise.reject(new Error(opts.upsertThrows));
        if (opts.onUpsert) opts.onUpsert(payload);
        return Promise.resolve({ ok: true });
      }
    }
  };
  var sandbox = { window: win, document: dom.document, console: { warn: function () {}, log: function () {} },
    Promise: Promise, CSS: null, setTimeout: setTimeout };
  // `KM` is bound as well as `window`: in a browser `window.KM` IS the global `KM`, and the page uses the bare
  // form the other pages use. Binding only `window` would make the shim stricter than the environment.
  var code = fs.readFileSync(path.join(ROOT, 'assets/js/pages/site-priority.js'), 'utf8');
  var fn = new Function('window', 'document', 'console', 'CSS', 'KM', code);
  fn(win, dom.document, sandbox.console, null, win.KM);
  return { win: win, dom: dom, calls: calls, api: win.KM.sitePriority, hooks: win.KM._hooks };
}

