const fs = require('node:fs');
const path = require('node:path');
const { extract } = require('../tests/ad4/extract.cjs');
const root = path.resolve(__dirname, '../..');
const source = fs.readFileSync(path.join(root, 'assets/specs/active/apps-script/18_sku_regional_handlers.gs'), 'utf8');
const output = '// Generated by assets/tools/build-inventory-sku-identity.cjs. Do not edit.\n' +
  '(function (root) {\n' + extract(source, n => n === 'skuInventoryAliasRows_', () => false)[0].text + '\n' +
  'root.KM = root.KM || {}; root.KM.inventorySkuIdentity = { expand: skuInventoryAliasRows_ };\n' +
  '})(window);\n';
const target = path.join(root, 'assets/js/utils/inventory-sku-identity.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output.replace(/\r\n/g, '\n')) throw new Error('Inventory SKU helper is out of date');
} else fs.writeFileSync(target, output);
